import Foundation

// MARK: - Synthesis Options & Artifact Models

public enum PersistenceBackendKind: String, CaseIterable, Codable, Identifiable, Sendable {
    case swiftData = "SwiftData (@Model)"
    case sqlite3StrictDDL = "SQLite3 STRICT + FTS5 Migration"
    case coreDataXML = "CoreData (.xcdatamodeld XML)"
    case swiftActorRepository = "Swift 6 Actor Repository + Reducer"

    public var id: String { rawValue }

    public var suggestedFilename: String {
        switch self {
        case .swiftData: "GeneratedSwiftDataModels.swift"
        case .sqlite3StrictDDL: "V001__InitialSchema.sql"
        case .coreDataXML: "DomainModel.xcdatamodel/contents"
        case .swiftActorRepository: "DomainActorRepository.swift"
        }
    }

    public var languageIdentifier: String {
        switch self {
        case .swiftData, .swiftActorRepository: "swift"
        case .sqlite3StrictDDL: "sql"
        case .coreDataXML: "xml"
        }
    }
}

public struct PersistenceSynthesisOptions: Codable, Hashable, Sendable {
    public var includeCommentsAndDocstrings: Bool
    public var enableCloudKitCompatibleOptionals: Bool
    public var includeFTS5VirtualTables: Bool
    public var includeUpdatedAtTriggers: Bool
    public var includePredicateQueryHelpers: Bool
    public var generateSampleSeedStatements: Bool

    public init(
        includeCommentsAndDocstrings: Bool = true,
        enableCloudKitCompatibleOptionals: Bool = false,
        includeFTS5VirtualTables: Bool = true,
        includeUpdatedAtTriggers: Bool = true,
        includePredicateQueryHelpers: Bool = true,
        generateSampleSeedStatements: Bool = false
    ) {
        self.includeCommentsAndDocstrings = includeCommentsAndDocstrings
        self.enableCloudKitCompatibleOptionals = enableCloudKitCompatibleOptionals
        self.includeFTS5VirtualTables = includeFTS5VirtualTables
        self.includeUpdatedAtTriggers = includeUpdatedAtTriggers
        self.includePredicateQueryHelpers = includePredicateQueryHelpers
        self.generateSampleSeedStatements = generateSampleSeedStatements
    }
}

public struct PersistenceSynthesisArtifact: Identifiable, Codable, Hashable, Sendable {
    public var id: String { "\(backend.rawValue):\(filename)" }
    public var backend: PersistenceBackendKind
    public var filename: String
    public var sourceCode: String
    public var entityCount: Int
    public var lineCount: Int
    public var warnings: [String]

    public init(
        backend: PersistenceBackendKind,
        filename: String,
        sourceCode: String,
        entityCount: Int,
        warnings: [String] = []
    ) {
        self.backend = backend
        self.filename = filename
        self.sourceCode = sourceCode
        self.entityCount = entityCount
        self.lineCount = sourceCode.split(separator: "\n", omittingEmptySubsequences: false).count
        self.warnings = warnings
    }
}

// MARK: - PersistenceCodeSynthesizer

public enum PersistenceCodeSynthesizer {
    public static func synthesize(
        workspace: DataSchemaWorkspace,
        backend: PersistenceBackendKind,
        options: PersistenceSynthesisOptions = PersistenceSynthesisOptions()
    ) -> PersistenceSynthesisArtifact {
        switch backend {
        case .swiftData:
            return synthesizeSwiftData(workspace: workspace, options: options)
        case .sqlite3StrictDDL:
            return synthesizeSQLiteStrictDDL(workspace: workspace, options: options)
        case .coreDataXML:
            return synthesizeCoreDataXML(workspace: workspace, options: options)
        case .swiftActorRepository:
            return synthesizeActorRepositoryAndReducer(workspace: workspace, options: options)
        }
    }

    public static func synthesizeAllBackends(
        workspace: DataSchemaWorkspace,
        options: PersistenceSynthesisOptions = PersistenceSynthesisOptions()
    ) -> [PersistenceSynthesisArtifact] {
        PersistenceBackendKind.allCases.map { backend in
            synthesize(workspace: workspace, backend: backend, options: options)
        }
    }

    // MARK: - 1) SwiftData @Model Synthesizer

    public static func synthesizeSwiftData(
        workspace: DataSchemaWorkspace,
        options: PersistenceSynthesisOptions = PersistenceSynthesisOptions()
    ) -> PersistenceSynthesisArtifact {
        var warnings: [String] = []
        var lines: [String] = [
            "import Foundation",
            "import SwiftData",
            ""
        ]

        if options.includeCommentsAndDocstrings {
            lines.insert("// Generated by ChiefKit Studio 3.0 — SwiftData Persistence Synthesizer", at: 0)
            lines.insert("// Workspace: \(workspace.name) (v\(workspace.schemaVersion))", at: 1)
        }

        // Emit closed Codable enums first
        for entity in workspace.entities {
            for attr in entity.attributes {
                if case .enumCases(let cases) = attr.fieldType {
                    let enumName = "\(entity.name)\(SchemaNamingHelpers.pascalCase(attr.name))"
                    lines.append("public enum \(enumName): String, Codable, CaseIterable, Sendable {")
                    let sanitizedCases = cases.isEmpty ? ["unspecified"] : cases
                    for rawCase in sanitizedCases {
                        let swiftIdent = sanitizeSwiftCaseIdentifier(rawCase)
                        lines.append("    case \(swiftIdent) = \"\(escapeDoubleQuotes(rawCase))\"")
                    }
                    lines.append("}")
                    lines.append("")
                }
            }
        }

        // Emit @Model classes
        for entity in workspace.entities {
            let outgoing = workspace.outgoingRelationships(from: entity.name)
            let incoming = workspace.incomingRelationships(to: entity.name)
            let fkColumns = Set(incoming.filter { $0.kind != .manyToMany }.map(\.foreignKeyColumn))

            if options.includeCommentsAndDocstrings && !entity.summary.isEmpty {
                lines.append("/// \(entity.summary)")
            }
            lines.append("@Model")
            lines.append("public final class \(entity.name) {")

            var initParams: [(paramDecl: String, assignLine: String)] = []

            for attr in entity.attributes {
                // Skip raw foreign key UUID scalars if modeled via @Relationship reference
                if fkColumns.contains(attr.name) && !attr.isPrimaryKey {
                    continue
                }

                let isOpt = attr.isNullable || (options.enableCloudKitCompatibleOptionals && !attr.isPrimaryKey)
                let swiftType = attr.fieldType.swiftTypeName(
                    entityName: entity.name,
                    attributeName: attr.name,
                    isOptional: isOpt
                )
                let propName = SchemaNamingHelpers.camelCase(attr.name)

                if options.includeCommentsAndDocstrings && !attr.documentation.isEmpty {
                    lines.append("    /// \(attr.documentation)")
                }

                var attributeTraits: [String] = []
                if (attr.isPrimaryKey || attr.isUnique) && !options.enableCloudKitCompatibleOptionals {
                    attributeTraits.append(".unique")
                }
                if case .vectorEmbedding = attr.fieldType {
                    attributeTraits.append(".externalStorage")
                } else if case .jsonBlob = attr.fieldType {
                    attributeTraits.append(".externalStorage")
                }

                if !attributeTraits.isEmpty {
                    lines.append("    @Attribute(\(attributeTraits.joined(separator: ", ")))")
                }

                lines.append("    public var \(propName): \(swiftType)")

                let defaultExpr = defaultSwiftExpr(for: attr, entityName: entity.name, isOptional: isOpt)
                let paramStr = defaultExpr.map { "\(propName): \(swiftType) = \($0)" } ?? "\(propName): \(swiftType)"
                initParams.append((paramStr, "        self.\(propName) = \(propName)"))
            }

            // Audit & tenant properties if enabled and not already present
            let declaredNames = Set(entity.attributes.map(\.name))
            if entity.isTenantScoped && !declaredNames.contains("tenant_id") {
                lines.append("    public var tenantID: UUID")
                initParams.append(("tenantID: UUID = UUID()", "        self.tenantID = tenantID"))
            }
            if entity.isAuditedWithTimestamps {
                if !declaredNames.contains("created_at") {
                    lines.append("    public var createdAt: Date")
                    initParams.append(("createdAt: Date = Date()", "        self.createdAt = createdAt"))
                }
                if !declaredNames.contains("updated_at") {
                    lines.append("    public var updatedAt: Date")
                    initParams.append(("updatedAt: Date = Date()", "        self.updatedAt = updatedAt"))
                }
            }
            if entity.isSoftDeletable && !declaredNames.contains("deleted_at") {
                lines.append("    public var deletedAt: Date?")
                initParams.append(("deletedAt: Date? = nil", "        self.deletedAt = deletedAt"))
            }

            // Outgoing @Relationship declarations
            for rel in outgoing {
                let relProp = SchemaNamingHelpers.camelCase(rel.name)
                let inverseClause: String
                if let inv = rel.inverseName, !inv.isEmpty {
                    inverseClause = ", inverse: \\\(rel.targetEntityName).\(SchemaNamingHelpers.camelCase(inv))"
                } else {
                    warnings.append("Relationship '\(entity.name).\(rel.name)' has no inverseName; SwiftData may create implicit join metadata.")
                    inverseClause = ""
                }
                lines.append("    @Relationship(deleteRule: \(rel.deleteRule.swiftDataRuleName)\(inverseClause))")
                switch rel.kind {
                case .oneToOne:
                    let typeStr = (rel.isOptional || options.enableCloudKitCompatibleOptionals) ? "\(rel.targetEntityName)?" : rel.targetEntityName
                    let defaultStr = typeStr.hasSuffix("?") ? " = nil" : ""
                    lines.append("    public var \(relProp): \(typeStr)")
                    initParams.append(("\(relProp): \(typeStr)\(defaultStr)", "        self.\(relProp) = \(relProp)"))
                case .oneToMany, .manyToMany:
                    lines.append("    public var \(relProp): [\(rel.targetEntityName)]")
                    initParams.append(("\(relProp): [\(rel.targetEntityName)] = []", "        self.\(relProp) = \(relProp)"))
                }
            }

            // Incoming inverse back-references
            for rel in incoming where rel.sourceEntityName != entity.name {
                guard let inv = rel.inverseName, !inv.isEmpty else { continue }
                let invProp = SchemaNamingHelpers.camelCase(inv)
                if rel.kind == .manyToMany {
                    lines.append("    public var \(invProp): [\(rel.sourceEntityName)]")
                    initParams.append(("\(invProp): [\(rel.sourceEntityName)] = []", "        self.\(invProp) = \(invProp)"))
                } else {
                    lines.append("    public var \(invProp): \(rel.sourceEntityName)?")
                    initParams.append(("\(invProp): \(rel.sourceEntityName)? = nil", "        self.\(invProp) = \(invProp)"))
                }
            }

            lines.append("")
            lines.append("    public init(")
            for (idx, item) in initParams.enumerated() {
                let comma = idx < initParams.count - 1 ? "," : ""
                lines.append("        \(item.paramDecl)\(comma)")
            }
            lines.append("    ) {")
            for item in initParams {
                lines.append(item.assignLine)
            }
            lines.append("    }")

            if options.includePredicateQueryHelpers {
                lines.append(contentsOf: buildSwiftDataPredicateHelpers(for: entity))
            }

            lines.append("}")
            lines.append("")
        }

        // Emit ModelContainer bootstrapper
        let containerName = "\(SchemaNamingHelpers.pascalCase(workspace.namespacePrefix))SchemaContainer"
        let modelList = workspace.entities.map { "\($0.name).self" }.joined(separator: ",\n            ")
        lines.append("public enum \(containerName) {")
        lines.append("    public static let schema = Schema([")
        lines.append("            \(modelList)")
        lines.append("    ], version: Schema.Version(\(workspace.schemaVersion), 0, 0))")
        lines.append("")
        lines.append("    public static func makeContainer(inMemoryOnly: Bool = false) throws -> ModelContainer {")
        lines.append("        let configuration = ModelConfiguration(")
        lines.append("            \"\(escapeDoubleQuotes(workspace.name))\",")
        lines.append("            schema: schema,")
        lines.append("            isStoredInMemoryOnly: inMemoryOnly")
        lines.append("        )")
        lines.append("        return try ModelContainer(for: schema, configurations: [configuration])")
        lines.append("    }")
        lines.append("}")

        return PersistenceSynthesisArtifact(
            backend: .swiftData,
            filename: "\(SchemaNamingHelpers.pascalCase(workspace.namespacePrefix))SwiftDataModels.swift",
            sourceCode: lines.joined(separator: "\n"),
            entityCount: workspace.entities.count,
            warnings: warnings
        )
    }

    private static func buildSwiftDataPredicateHelpers(for entity: SchemaEntity) -> [String] {
        var helperLines: [String] = []
        if let pk = entity.primaryKeyAttribute, pk.fieldType == .uuid {
            let pkProp = SchemaNamingHelpers.camelCase(pk.name)
            helperLines.append("")
            helperLines.append("    public static func byIDDescriptor(_ targetID: UUID) -> FetchDescriptor<\(entity.name)> {")
            helperLines.append("        var descriptor = FetchDescriptor<\(entity.name)>(")
            helperLines.append("            predicate: #Predicate<\(entity.name)> { row in row.\(pkProp) == targetID }")
            helperLines.append("        )")
            helperLines.append("        descriptor.fetchLimit = 1")
            helperLines.append("        return descriptor")
            helperLines.append("    }")
        }

        if let searchable = entity.attributes.first(where: { $0.isFullTextSearchable && !$0.isNullable }) {
            let prop = SchemaNamingHelpers.camelCase(searchable.name)
            helperLines.append("")
            helperLines.append("    public static func searchDescriptor(matching query: String, limit: Int = 50) -> FetchDescriptor<\(entity.name)> {")
            helperLines.append("        var descriptor = FetchDescriptor<\(entity.name)>(")
            helperLines.append("            predicate: #Predicate<\(entity.name)> { row in")
            helperLines.append("                query.isEmpty || row.\(prop).localizedStandardContains(query)")
            helperLines.append("            }")
            helperLines.append("        )")
            helperLines.append("        descriptor.fetchLimit = max(1, limit)")
            helperLines.append("        return descriptor")
            helperLines.append("    }")
        }
        return helperLines
    }

    // MARK: - 2) Strict SQLite3 DDL + Up/Down Migration SQL

    public static func synthesizeSQLiteStrictDDL(
        workspace: DataSchemaWorkspace,
        options: PersistenceSynthesisOptions = PersistenceSynthesisOptions()
    ) -> PersistenceSynthesisArtifact {
        let (orderedEntities, cyclicNames) = workspace.topologicalSortEntities()
        var warnings: [String] = []
        if !cyclicNames.isEmpty {
            warnings.append("Cyclic FK dependencies detected (\(cyclicNames.joined(separator: ", "))); verify deferred foreign keys during bulk load.")
        }

        var upLines: [String] = [
            "-- ============================================================================",
            "-- ChiefKit Studio 3.0 — SQLite 3.37+ STRICT Migration Script",
            "-- Workspace: \(workspace.name) | Schema Version: v\(workspace.schemaVersion)",
            "-- ============================================================================",
            "-- +migrate Up",
            "PRAGMA foreign_keys = ON;",
            "PRAGMA journal_mode = WAL;",
            "PRAGMA synchronous = NORMAL;",
            ""
        ]

        var downStatements: [String] = []

        for entity in orderedEntities {
            if options.includeCommentsAndDocstrings && !entity.summary.isEmpty {
                upLines.append("-- Entity: \(entity.name) — \(entity.summary)")
            }
            upLines.append("CREATE TABLE IF NOT EXISTS \"\(entity.tableName)\" (")

            var tableLines: [String] = []
            let pks = entity.primaryKeys
            let singlePK = pks.count == 1 ? pks.first?.name : nil
            let declaredNames = Set(entity.attributes.map(\.name))

            for attr in entity.attributes {
                var colParts: [String] = [
                    "\"\(attr.name)\"",
                    attr.fieldType.sqliteStrictColumnType
                ]
                if attr.name == singlePK {
                    colParts.append("PRIMARY KEY")
                }
                if !attr.isNullable || attr.isPrimaryKey {
                    colParts.append("NOT NULL")
                }
                if attr.isUnique && attr.name != singlePK {
                    colParts.append("UNIQUE")
                }
                if let defClause = attr.defaultValue.sqliteDefaultClause {
                    colParts.append(defClause)
                }
                if let inlineCheck = sqliteInlineCheckClause(for: attr) {
                    colParts.append(inlineCheck)
                }
                tableLines.append("    " + colParts.joined(separator: " "))
            }

            // Synthesize incoming foreign key columns if omitted in attributes
            let incomingFKs = workspace.incomingRelationships(to: entity.name).filter { $0.kind != .manyToMany }
            for rel in incomingFKs where !declaredNames.contains(rel.foreignKeyColumn) {
                let nullability = rel.isOptional ? "" : " NOT NULL"
                tableLines.append("    \"\(rel.foreignKeyColumn)\" TEXT\(nullability)")
            }

            if entity.isTenantScoped && !declaredNames.contains("tenant_id") {
                tableLines.append("    \"tenant_id\" TEXT NOT NULL")
            }
            if entity.isAuditedWithTimestamps {
                if !declaredNames.contains("created_at") {
                    tableLines.append("    \"created_at\" TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))")
                }
                if !declaredNames.contains("updated_at") {
                    tableLines.append("    \"updated_at\" TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))")
                }
            }
            if entity.isSoftDeletable && !declaredNames.contains("deleted_at") {
                tableLines.append("    \"deleted_at\" TEXT")
            }

            if pks.count > 1 {
                let compositePKCols = pks.map { "\"\($0.name)\"" }.joined(separator: ", ")
                tableLines.append("    PRIMARY KEY (\(compositePKCols))")
            }

            // Entity-level constraints
            for constraint in entity.constraints {
                switch constraint.kind {
                case .compositeUnique:
                    let cols = constraint.columns.map { "\"\($0)\"" }.joined(separator: ", ")
                    tableLines.append("    CONSTRAINT \"\(constraint.name)\" UNIQUE (\(cols))")
                case .checkExpression, .numericBounds, .nonEmptyTrimmed:
                    tableLines.append("    CONSTRAINT \"\(constraint.name)\" CHECK (\(constraint.expression))")
                case .immutableOnceSet:
                    break
                }
            }

            // Foreign keys
            for rel in incomingFKs {
                guard let parent = workspace.entity(named: rel.sourceEntityName) else { continue }
                let parentPK = parent.primaryKeyAttribute?.name ?? "id"
                tableLines.append(
                    "    FOREIGN KEY (\"\(rel.foreignKeyColumn)\") REFERENCES \"\(parent.tableName)\"(\"\(parentPK)\") ON DELETE \(rel.deleteRule.sqliteAction) ON UPDATE CASCADE"
                )
            }

            upLines.append(tableLines.joined(separator: ",\n"))
            upLines.append(") STRICT;")
            upLines.append("")

            downStatements.append("DROP TABLE IF EXISTS \"\(entity.tableName)\";")

            // Single-column attribute indexes
            for attr in entity.attributes where attr.isIndexed && !attr.isPrimaryKey && !attr.isUnique {
                let idxName = "idx_\(entity.tableName)_\(attr.name)"
                upLines.append("CREATE INDEX IF NOT EXISTS \"\(idxName)\" ON \"\(entity.tableName)\" (\"\(attr.name)\");")
            }

            // Explicit composite / partial indexes
            for index in entity.indexes where index.kind != .fts5FullText && index.kind != .vectorHNSW {
                let uniqueKw = index.kind == .uniqueBTree ? "UNIQUE " : ""
                let cols = index.columns.map { "\"\($0)\"" }.joined(separator: ", ")
                let whereClause: String
                if let pred = index.wherePredicateSQL, !pred.isEmpty {
                    whereClause = " WHERE \(pred)"
                } else {
                    whereClause = ""
                }
                upLines.append("CREATE \(uniqueKw)INDEX IF NOT EXISTS \"\(index.name)\" ON \"\(entity.tableName)\" (\(cols))\(whereClause);")
            }

            // Updated_at automatic maintenance trigger
            if options.includeUpdatedAtTriggers && entity.isAuditedWithTimestamps {
                let pkCol = entity.primaryKeyAttribute?.name ?? "rowid"
                let trgName = "trg_\(entity.tableName)_updated_at"
                upLines.append("CREATE TRIGGER IF NOT EXISTS \"\(trgName)\"")
                upLines.append("AFTER UPDATE ON \"\(entity.tableName)\"")
                upLines.append("FOR EACH ROW WHEN NEW.\"updated_at\" = OLD.\"updated_at\"")
                upLines.append("BEGIN")
                upLines.append("    UPDATE \"\(entity.tableName)\" SET \"updated_at\" = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE \"\(pkCol)\" = NEW.\"\(pkCol)\";")
                upLines.append("END;")
                upLines.append("")
                downStatements.append("DROP TRIGGER IF EXISTS \"\(trgName)\";")
            }

            // FTS5 Full-Text Search virtual table & triggers
            let ftsCols = entity.attributes.filter(\.isFullTextSearchable).map(\.name)
            if options.includeFTS5VirtualTables && !ftsCols.isEmpty {
                let ftsTable = "\(entity.tableName)_fts"
                let pkCol = entity.primaryKeyAttribute?.name ?? "id"
                let quotedCols = (["\"\(pkCol)\" UNINDEXED"] + ftsCols.map { "\"\($0)\"" }).joined(separator: ", ")
                upLines.append("CREATE VIRTUAL TABLE IF NOT EXISTS \"\(ftsTable)\" USING fts5(\(quotedCols), tokenize = 'unicode61 remove_diacritics 2');")

                let colList = ([pkCol] + ftsCols).map { "\"\($0)\"" }.joined(separator: ", ")
                let newValues = ([pkCol] + ftsCols).map { "NEW.\"\($0)\"" }.joined(separator: ", ")

                upLines.append("CREATE TRIGGER IF NOT EXISTS \"trg_\(ftsTable)_ai\" AFTER INSERT ON \"\(entity.tableName)\" BEGIN")
                upLines.append("    INSERT INTO \"\(ftsTable)\" (\(colList)) VALUES (\(newValues));")
                upLines.append("END;")

                upLines.append("CREATE TRIGGER IF NOT EXISTS \"trg_\(ftsTable)_ad\" AFTER DELETE ON \"\(entity.tableName)\" BEGIN")
                upLines.append("    DELETE FROM \"\(ftsTable)\" WHERE \"\(pkCol)\" = OLD.\"\(pkCol)\";")
                upLines.append("END;")
                upLines.append("")

                downStatements.append("DROP TRIGGER IF EXISTS \"trg_\(ftsTable)_ad\";")
                downStatements.append("DROP TRIGGER IF EXISTS \"trg_\(ftsTable)_ai\";")
                downStatements.append("DROP TABLE IF EXISTS \"\(ftsTable)\";")
            }
        }

        // Many-to-Many Associative Join Tables
        for rel in workspace.relationships where rel.kind == .manyToMany {
            guard let source = workspace.entity(named: rel.sourceEntityName),
                  let target = workspace.entity(named: rel.targetEntityName) else { continue }
            let joinTable = rel.joinTableName ?? "\(source.tableName)_\(target.tableName)_links"
            let leftCol = "\(SchemaNamingHelpers.snakeCase(source.name))_id"
            let rightCol = "\(SchemaNamingHelpers.snakeCase(target.name))_id"
            let sourcePK = source.primaryKeyAttribute?.name ?? "id"
            let targetPK = target.primaryKeyAttribute?.name ?? "id"

            upLines.append("-- Associative Join Table for \(source.name) <-> \(target.name)")
            upLines.append("CREATE TABLE IF NOT EXISTS \"\(joinTable)\" (")
            upLines.append("    \"\(leftCol)\" TEXT NOT NULL,")
            upLines.append("    \"\(rightCol)\" TEXT NOT NULL,")
            upLines.append("    \"linked_at\" TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),")
            upLines.append("    PRIMARY KEY (\"\(leftCol)\", \"\(rightCol)\"),")
            upLines.append("    FOREIGN KEY (\"\(leftCol)\") REFERENCES \"\(source.tableName)\"(\"\(sourcePK)\") ON DELETE CASCADE,")
            upLines.append("    FOREIGN KEY (\"\(rightCol)\") REFERENCES \"\(target.tableName)\"(\"\(targetPK)\") ON DELETE CASCADE")
            upLines.append(") STRICT;")
            upLines.append("CREATE INDEX IF NOT EXISTS \"idx_\(joinTable)_\(rightCol)\" ON \"\(joinTable)\" (\"\(rightCol)\");")
            upLines.append("")

            downStatements.append("DROP TABLE IF EXISTS \"\(joinTable)\";")
        }

        upLines.append("-- +migrate Down")
        upLines.append(contentsOf: downStatements.reversed())

        return PersistenceSynthesisArtifact(
            backend: .sqlite3StrictDDL,
            filename: "V\(String(format: "%03d", workspace.schemaVersion))__\(SchemaNamingHelpers.snakeCase(workspace.name)).sql",
            sourceCode: upLines.joined(separator: "\n"),
            entityCount: workspace.entities.count,
            warnings: warnings
        )
    }

    /// Generates incremental `ALTER TABLE` SQL diff statements between two versions of a `DataSchemaWorkspace`.
    public static func synthesizeDiffMigrationSQL(
        from baseline: DataSchemaWorkspace,
        to target: DataSchemaWorkspace
    ) -> String {
        var sql: [String] = [
            "-- Incremental Schema Diff: \(baseline.name) v\(baseline.schemaVersion) -> v\(target.schemaVersion)",
            "PRAGMA foreign_keys = ON;",
            ""
        ]

        let oldByName = Dictionary(uniqueKeysWithValues: baseline.entities.map { ($0.name, $0) })
        let newByName = Dictionary(uniqueKeysWithValues: target.entities.map { ($0.name, $0) })

        for entity in target.entities {
            guard let previous = oldByName[entity.name] else {
                sql.append("-- Added entity \(entity.name): run full CREATE TABLE for \"\(entity.tableName)\"")
                let singleWorkspace = DataSchemaWorkspace(
                    name: target.name,
                    schemaVersion: target.schemaVersion,
                    namespacePrefix: target.namespacePrefix,
                    entities: [entity],
                    relationships: []
                )
                sql.append(synthesizeSQLiteStrictDDL(workspace: singleWorkspace).sourceCode)
                continue
            }

            let oldAttrNames = Set(previous.attributes.map(\.name))
            for attr in entity.attributes where !oldAttrNames.contains(attr.name) {
                let colType = attr.fieldType.sqliteStrictColumnType
                let defClause = attr.defaultValue.sqliteDefaultClause.map { " \($0)" } ?? (attr.isNullable ? "" : " DEFAULT ''")
                let notNull = attr.isNullable ? "" : " NOT NULL"
                sql.append("ALTER TABLE \"\(entity.tableName)\" ADD COLUMN \"\(attr.name)\" \(colType)\(notNull)\(defClause);")
            }

            let newAttrNames = Set(entity.attributes.map(\.name))
            for oldAttr in previous.attributes where !newAttrNames.contains(oldAttr.name) {
                sql.append("ALTER TABLE \"\(entity.tableName)\" DROP COLUMN \"\(oldAttr.name)\";")
            }
        }

        for oldEntity in baseline.entities where newByName[oldEntity.name] == nil {
            sql.append("DROP TABLE IF EXISTS \"\(oldEntity.tableName)\";")
        }

        return sql.joined(separator: "\n")
    }

    private static func sqliteInlineCheckClause(for attr: SchemaAttribute) -> String? {
        switch attr.fieldType {
        case .string(let maxLen):
            if let maxLen, maxLen > 0 {
                return "CHECK (length(\"\(attr.name)\") <= \(maxLen))"
            }
            return nil
        case .bool:
            return "CHECK (\"\(attr.name)\" IN (0, 1))"
        case .enumCases(let cases) where !cases.isEmpty:
            let quoted = cases.map { "'\($0.replacingOccurrences(of: "'", with: "''"))'" }.joined(separator: ", ")
            return "CHECK (\"\(attr.name)\" IN (\(quoted)))"
        case .jsonBlob:
            return "CHECK (json_valid(\"\(attr.name)\") = 1)"
        default:
            return nil
        }
    }

    // MARK: - 3) CoreData .xcdatamodeld XML Synthesizer

    public static func synthesizeCoreDataXML(
        workspace: DataSchemaWorkspace,
        options: PersistenceSynthesisOptions = PersistenceSynthesisOptions()
    ) -> PersistenceSynthesisArtifact {
        var xml: [String] = [
            "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>",
            "<model type=\"com.apple.IDECoreDataModeler.DataModel\" documentVersion=\"1.0\" lastSavedToolsVersion=\"23507\" systemVersion=\"24A335\" minimumToolsVersion=\"Automatic\" sourceLanguage=\"Swift\" usedWithSwiftData=\"NO\" userDefinedModelVersionIdentifier=\"v\(workspace.schemaVersion)\">"
        ]

        for entity in workspace.entities {
            let className = "\(workspace.namespacePrefix)\(entity.name)MO"
            xml.append("    <entity name=\"\(escapeXML(entity.name))\" representedClassName=\"\(escapeXML(className))\" syncable=\"YES\" codeGenerationType=\"class\">")

            let incoming = workspace.incomingRelationships(to: entity.name)
            let fkCols = Set(incoming.filter { $0.kind != .manyToMany }.map(\.foreignKeyColumn))

            for attr in entity.attributes where !fkCols.contains(attr.name) || attr.isPrimaryKey {
                let propName = SchemaNamingHelpers.camelCase(attr.name)
                let cdType = attr.fieldType.coreDataAttributeType
                let optionalFlag = (attr.isNullable || options.enableCloudKitCompatibleOptionals) ? "YES" : "NO"
                let scalarFlag = (cdType == "Integer 64" || cdType == "Double" || cdType == "Boolean") ? " usesScalarValueType=\"YES\"" : ""
                xml.append("        <attribute name=\"\(escapeXML(propName))\" optional=\"\(optionalFlag)\" attributeType=\"\(cdType)\"\(scalarFlag)/>")
            }

            if entity.isAuditedWithTimestamps {
                xml.append("        <attribute name=\"createdAt\" optional=\"NO\" attributeType=\"Date\" usesScalarValueType=\"NO\"/>")
                xml.append("        <attribute name=\"updatedAt\" optional=\"NO\" attributeType=\"Date\" usesScalarValueType=\"NO\"/>")
            }

            // Outgoing relationships
            for rel in workspace.outgoingRelationships(from: entity.name) {
                let relName = SchemaNamingHelpers.camelCase(rel.name)
                let toMany = (rel.kind == .oneToMany || rel.kind == .manyToMany) ? "YES" : "NO"
                let maxCountAttr = toMany == "NO" ? " maxCount=\"1\"" : ""
                let optAttr = (rel.isOptional || toMany == "YES") ? "YES" : "NO"
                let invAttr: String
                if let inv = rel.inverseName, !inv.isEmpty {
                    invAttr = " inverseName=\"\(escapeXML(SchemaNamingHelpers.camelCase(inv)))\" inverseEntity=\"\(escapeXML(rel.targetEntityName))\""
                } else {
                    invAttr = ""
                }
                xml.append(
                    "        <relationship name=\"\(escapeXML(relName))\" optional=\"\(optAttr)\"\(maxCountAttr) toMany=\"\(toMany)\" deletionRule=\"\(rel.deleteRule.coreDataRuleName)\" destinationEntity=\"\(escapeXML(rel.targetEntityName))\"\(invAttr)/>"
                )
            }

            // Incoming inverse relationships
            for rel in incoming where rel.sourceEntityName != entity.name {
                guard let inv = rel.inverseName, !inv.isEmpty else { continue }
                let invProp = SchemaNamingHelpers.camelCase(inv)
                let toMany = rel.kind == .manyToMany ? "YES" : "NO"
                let maxCountAttr = toMany == "NO" ? " maxCount=\"1\"" : ""
                xml.append(
                    "        <relationship name=\"\(escapeXML(invProp))\" optional=\"YES\"\(maxCountAttr) toMany=\"\(toMany)\" deletionRule=\"Nullify\" destinationEntity=\"\(escapeXML(rel.sourceEntityName))\" inverseName=\"\(escapeXML(SchemaNamingHelpers.camelCase(rel.name)))\" inverseEntity=\"\(escapeXML(rel.sourceEntityName))\"/>"
                )
            }

            // Uniqueness constraints
            let uniqueAttrs = entity.attributes.filter { ($0.isPrimaryKey || $0.isUnique) && !options.enableCloudKitCompatibleOptionals }
            if !uniqueAttrs.isEmpty {
                xml.append("        <uniquenessConstraints>")
                for uAttr in uniqueAttrs {
                    xml.append("            <uniquenessConstraint>")
                    xml.append("                <constraint value=\"\(escapeXML(SchemaNamingHelpers.camelCase(uAttr.name)))\"/>")
                    xml.append("            </uniquenessConstraint>")
                }
                xml.append("        </uniquenessConstraints>")
            }

            // Fetch indexes
            for index in entity.indexes where index.kind == .btree || index.kind == .uniqueBTree {
                xml.append("        <fetchIndex name=\"\(escapeXML(index.name))\">")
                for col in index.columns {
                    let prop = SchemaNamingHelpers.camelCase(col)
                    xml.append("            <fetchIndexElement property=\"\(escapeXML(prop))\" type=\"Binary\" order=\"ascending\"/>")
                }
                xml.append("        </fetchIndex>")
            }

            xml.append("    </entity>")
        }

        xml.append("    <elements>")
        for entity in workspace.entities {
            let h = max(74, 44 + entity.attributes.count * 15)
            xml.append("        <element name=\"\(escapeXML(entity.name))\" positionX=\"\(Int(entity.position.x))\" positionY=\"\(Int(entity.position.y))\" width=\"160\" height=\"\(h)\"/>")
        }
        xml.append("    </elements>")
        xml.append("</model>")

        return PersistenceSynthesisArtifact(
            backend: .coreDataXML,
            filename: "\(SchemaNamingHelpers.pascalCase(workspace.name)).xcdatamodeld/contents",
            sourceCode: xml.joined(separator: "\n"),
            entityCount: workspace.entities.count
        )
    }

    // MARK: - 4) Pure Swift 6 Actor In-Memory + JSON File Repository + SwiftState Reducer

    public static func synthesizeActorRepositoryAndReducer(
        workspace: DataSchemaWorkspace,
        options: PersistenceSynthesisOptions = PersistenceSynthesisOptions()
    ) -> PersistenceSynthesisArtifact {
        let prefix = SchemaNamingHelpers.pascalCase(workspace.namespacePrefix.isEmpty ? "Domain" : workspace.namespacePrefix)
        var lines: [String] = [
            "// Generated by ChiefKit Studio 3.0 — Swift 6 Strict Concurrency Actor Repository & Reducer",
            "import Foundation",
            ""
        ]

        // 1) Value-type Sendable DTOs + Closed Enums
        for entity in workspace.entities {
            for attr in entity.attributes {
                if case .enumCases(let cases) = attr.fieldType {
                    let enumName = "\(entity.name)\(SchemaNamingHelpers.pascalCase(attr.name))"
                    lines.append("public enum \(enumName): String, Codable, CaseIterable, Hashable, Sendable {")
                    for rawCase in (cases.isEmpty ? ["unspecified"] : cases) {
                        lines.append("    case \(sanitizeSwiftCaseIdentifier(rawCase)) = \"\(escapeDoubleQuotes(rawCase))\"")
                    }
                    lines.append("}")
                    lines.append("")
                }
            }

            let recordName = "\(entity.name)Record"
            lines.append("public struct \(recordName): Identifiable, Codable, Hashable, Sendable {")

            var initDecls: [String] = []
            var initAssigns: [String] = []
            var hasIDProperty = false

            for attr in entity.attributes {
                let propName = SchemaNamingHelpers.camelCase(attr.name)
                if propName == "id" { hasIDProperty = true }
                let swiftType = attr.fieldType.swiftTypeName(
                    entityName: entity.name,
                    attributeName: attr.name,
                    isOptional: attr.isNullable
                )
                lines.append("    public var \(propName): \(swiftType)")
                let defExpr = defaultSwiftExpr(for: attr, entityName: entity.name, isOptional: attr.isNullable)
                let param = defExpr.map { "\(propName): \(swiftType) = \($0)" } ?? "\(propName): \(swiftType)"
                initDecls.append(param)
                initAssigns.append("        self.\(propName) = \(propName)")
            }

            if !hasIDProperty {
                lines.insert("    public var id: UUID", at: lines.count - entity.attributes.count)
                initDecls.insert("id: UUID = UUID()", at: 0)
                initAssigns.insert("        self.id = id", at: 0)
            }

            if entity.isAuditedWithTimestamps {
                let existingProps = Set(entity.attributes.map { SchemaNamingHelpers.camelCase($0.name) })
                if !existingProps.contains("createdAt") {
                    lines.append("    public var createdAt: Date")
                    initDecls.append("createdAt: Date = Date()")
                    initAssigns.append("        self.createdAt = createdAt")
                }
                if !existingProps.contains("updatedAt") {
                    lines.append("    public var updatedAt: Date")
                    initDecls.append("updatedAt: Date = Date()")
                    initAssigns.append("        self.updatedAt = updatedAt")
                }
            }

            lines.append("")
            lines.append("    public init(\(initDecls.joined(separator: ", "))) {")
            lines.append(contentsOf: initAssigns)
            lines.append("    }")
            lines.append("}")
            lines.append("")
        }

        // 2) Snapshot envelope
        let snapshotType = "\(prefix)DatabaseSnapshot"
        lines.append("public struct \(snapshotType): Codable, Equatable, Sendable {")
        lines.append("    public var schemaVersion: Int")
        for entity in workspace.entities {
            let bucket = SchemaNamingHelpers.camelCase(entity.tableName)
            lines.append("    public var \(bucket): [UUID: \(entity.name)Record]")
        }
        lines.append("")
        lines.append("    public init(schemaVersion: Int = \(workspace.schemaVersion)) {")
        lines.append("        self.schemaVersion = schemaVersion")
        for entity in workspace.entities {
            let bucket = SchemaNamingHelpers.camelCase(entity.tableName)
            lines.append("        self.\(bucket) = [:]")
        }
        lines.append("    }")
        lines.append("}")
        lines.append("")

        // 3) Swift 6 Actor In-Memory + Atomic JSON File Repository
        let repoName = "\(prefix)ActorRepository"
        lines.append("public actor \(repoName) {")
        lines.append("    private var snapshot: \(snapshotType)")
        lines.append("    private let storageURL: URL?")
        lines.append("")
        lines.append("    public init(storageURL: URL? = nil, initialSnapshot: \(snapshotType) = \(snapshotType)()) {")
        lines.append("        self.storageURL = storageURL")
        lines.append("        self.snapshot = initialSnapshot")
        lines.append("    }")
        lines.append("")
        lines.append("    public func loadFromDisk() throws {")
        lines.append("        guard let url = storageURL, FileManager.default.fileExists(atPath: url.path) else { return }")
        lines.append("        let data = try Data(contentsOf: url)")
        lines.append("        let decoder = JSONDecoder()")
        lines.append("        decoder.dateDecodingStrategy = .iso8601")
        lines.append("        self.snapshot = try decoder.decode(\(snapshotType).self, from: data)")
        lines.append("    }")
        lines.append("")
        lines.append("    public func flushToDisk() throws {")
        lines.append("        guard let url = storageURL else { return }")
        lines.append("        let encoder = JSONEncoder()")
        lines.append("        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]")
        lines.append("        encoder.dateEncodingStrategy = .iso8601")
        lines.append("        let data = try encoder.encode(snapshot)")
        lines.append("        try data.write(to: url, options: .atomic)")
        lines.append("    }")
        lines.append("")
        lines.append("    public func exportSnapshot() -> \(snapshotType) {")
        lines.append("        snapshot")
        lines.append("    }")

        for entity in workspace.entities {
            let bucket = SchemaNamingHelpers.camelCase(entity.tableName)
            let recordName = "\(entity.name)Record"
            lines.append("")
            lines.append("    // MARK: \(entity.name) CRUD")
            lines.append("    public func upsert\(entity.name)(_ record: \(recordName)) throws {")
            lines.append("        snapshot.\(bucket)[record.id] = record")
            lines.append("        try flushToDisk()")
            lines.append("    }")
            lines.append("")
            lines.append("    public func find\(entity.name)(id: UUID) -> \(recordName)? {")
            lines.append("        snapshot.\(bucket)[id]")
            lines.append("    }")
            lines.append("")
            lines.append("    public func list\(SchemaNamingHelpers.pascalCase(entity.tableName))() -> [\(recordName)] {")
            lines.append("        Array(snapshot.\(bucket).values)")
            lines.append("    }")
            lines.append("")
            lines.append("    public func delete\(entity.name)(id: UUID) throws {")
            lines.append("        snapshot.\(bucket).removeValue(forKey: id)")
            lines.append("        try flushToDisk()")
            lines.append("    }")
        }
        lines.append("}")
        lines.append("")

        // 4) Unidirectional SwiftState State + Action + Pure Reducer
        let stateName = "\(prefix)DomainState"
        let actionName = "\(prefix)DomainAction"
        let reducerName = "\(prefix)DomainReducer"

        lines.append("public struct \(stateName): Codable, Equatable, Sendable {")
        lines.append("    public var snapshot: \(snapshotType)")
        lines.append("    public var isSyncing: Bool")
        lines.append("    public var lastErrorMessage: String?")
        lines.append("")
        lines.append("    public init(snapshot: \(snapshotType) = \(snapshotType)(), isSyncing: Bool = false, lastErrorMessage: String? = nil) {")
        lines.append("        self.snapshot = snapshot")
        lines.append("        self.isSyncing = isSyncing")
        lines.append("        self.lastErrorMessage = lastErrorMessage")
        lines.append("    }")
        lines.append("}")
        lines.append("")

        lines.append("public enum \(actionName): Equatable, Sendable {")
        lines.append("    case hydrate(\(snapshotType))")
        lines.append("    case setSyncing(Bool)")
        lines.append("    case recordError(String?)")
        for entity in workspace.entities {
            lines.append("    case upsert\(entity.name)(\(entity.name)Record)")
            lines.append("    case delete\(entity.name)(UUID)")
        }
        lines.append("}")
        lines.append("")

        lines.append("public enum \(reducerName) {")
        lines.append("    public static func reduce(state: inout \(stateName), action: \(actionName)) {")
        lines.append("        switch action {")
        lines.append("        case .hydrate(let loaded):")
        lines.append("            state.snapshot = loaded")
        lines.append("            state.isSyncing = false")
        lines.append("            state.lastErrorMessage = nil")
        lines.append("        case .setSyncing(let flag):")
        lines.append("            state.isSyncing = flag")
        lines.append("        case .recordError(let message):")
        lines.append("            state.lastErrorMessage = message")
        lines.append("            state.isSyncing = false")
        for entity in workspace.entities {
            let bucket = SchemaNamingHelpers.camelCase(entity.tableName)
            lines.append("        case .upsert\(entity.name)(let record):")
            lines.append("            state.snapshot.\(bucket)[record.id] = record")
            lines.append("        case .delete\(entity.name)(let targetID):")
            lines.append("            state.snapshot.\(bucket).removeValue(forKey: targetID)")
        }
        lines.append("        }")
        lines.append("    }")
        lines.append("}")

        return PersistenceSynthesisArtifact(
            backend: .swiftActorRepository,
            filename: "\(prefix)ActorRepository.swift",
            sourceCode: lines.joined(separator: "\n"),
            entityCount: workspace.entities.count
        )
    }

    // MARK: - Private Formatting Helpers

    private static func defaultSwiftExpr(for attr: SchemaAttribute, entityName: String, isOptional: Bool) -> String? {
        if let explicit = attr.defaultValue.swiftExpression {
            if case .enumCases(let cases) = attr.fieldType, case .literalString(let raw) = attr.defaultValue {
                let matching = cases.contains(raw) ? raw : (cases.first ?? raw)
                return ".\(sanitizeSwiftCaseIdentifier(matching))"
            }
            if case .decimal = attr.fieldType, case .literalDouble(let val) = attr.defaultValue {
                return "Decimal(\(val))"
            }
            return explicit
        }
        if isOptional {
            return "nil"
        }
        if attr.isPrimaryKey && attr.fieldType == .uuid {
            return "UUID()"
        }
        return nil
    }

    private static func sanitizeSwiftCaseIdentifier(_ raw: String) -> String {
        let camel = SchemaNamingHelpers.camelCase(raw)
        let cleaned = camel.isEmpty ? "unspecified" : camel
        let reserved: Set<String> = [
            "default", "class", "struct", "enum", "protocol", "import", "public",
            "private", "internal", "self", "Self", "Type", "return", "switch", "case", "in", "for"
        ]
        if reserved.contains(cleaned) {
            return "`\(cleaned)`"
        }
        if let first = cleaned.first, first.isNumber {
            return "case\(cleaned)"
        }
        return cleaned
    }

    private static func escapeDoubleQuotes(_ input: String) -> String {
        input
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
    }

    private static func escapeXML(_ input: String) -> String {
        input
            .replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
            .replacingOccurrences(of: "'", with: "&apos;")
    }
